describe('isReadOnlyAws with a target profile', () => {
  const target = { profile: 'target' }
  const allowed: [string, string][] = [
    ['profile with space', 'aws ec2 describe-instances --profile target'],
    ['profile with equals', 'aws ec2 describe-instances --profile=target'],
    ['profile before service', 'aws --profile target ec2 describe-regions'],
    ['profile in every segment', 'aws ec2 describe-instances --profile target | jq .'],
    ['profile in each aws call', 'aws s3 ls --profile target; aws sts get-caller-identity --profile target'],
  ]
  for (const [name, command] of allowed) {
    test(name, () => assert.equal(isReadOnlyAws(command, target), true, command))
  }
  const denied: [string, string][] = [
    ['no profile in segment', 'aws ec2 describe-instances'],
    ['[critical] other profile', 'aws ec2 describe-instances --profile other'],
    ['two profiles', 'aws s3 ls --profile target --profile other'],
    ['abbreviated profile flag', 'aws s3 ls --profile target --prof other'],
    ['profile without value', 'aws s3 ls --profile'],
    ['second segment without profile', 'aws s3 ls --profile target; aws sts get-caller-identity'],
    ['profile value is a flag', 'aws s3 ls --profile --region'],
  ]
  for (const [name, command] of denied) {
    test(name, () => assert.equal(isReadOnlyAws(command, target), false, command))
  }
  test('without opts the profile is not required', () => {
    assert.equal(isReadOnlyAws('aws ec2 describe-instances'), true)
  })
})
